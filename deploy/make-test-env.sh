#!/usr/bin/env bash
# deploy/make-test-env.sh
#
# Writes deploy/.env.test: a THROWAWAY env file for a test copy of the stack
# that can run next to (or without) the real one. Every secret is freshly
# generated and exists nowhere else, so data written by the test stack is
# unreadable with your real ENCRYPTION_KEY/BLIND_INDEX_KEY - which is exactly
# why test volumes must never be reused by the real stack. Always end a test
# with `down -v`.
#
# Idempotent: if .env.test already exists it is left alone (regenerating the DB
# password while a test volume still holds the old one would lock Django out).
# Use --force to overwrite.
#
# Usage (from anywhere):
#   deploy/make-test-env.sh [--force]
#   docker compose -f deploy/docker-compose.yml --env-file deploy/.env.test up -d --build
#   ...
#   docker compose -f deploy/docker-compose.yml --env-file deploy/.env.test down -v
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
out="$here/.env.test"

if [[ -e "$out" && "${1:-}" != "--force" ]]; then
  echo "$out already exists - leaving it alone (use --force to regenerate)."
  exit 0
fi

command -v python3 >/dev/null || { echo "python3 is required to generate keys." >&2; exit 1; }

gen() { python3 -c "$1"; }
secret_key=$(gen 'import secrets; print(secrets.token_urlsafe(64))')
db_password=$(gen 'import secrets; print(secrets.token_urlsafe(24))')
webhook=$(gen 'import secrets; print(secrets.token_urlsafe(32))')
# A Fernet key is 32 random bytes in url-safe base64.
fernet=$(gen 'import os,base64; print(base64.urlsafe_b64encode(os.urandom(32)).decode())')
blind=$(gen 'import secrets; print(secrets.token_hex(32))')

umask 077
cat > "$out" <<ENV
# deploy/.env.test - GENERATED by make-test-env.sh. Throwaway; gitignored.
APP_ENV_FILE=.env.test
COMPOSE_PROJECT_NAME=lanceraos-test
WEB_PORT=18000
IMAGE_TAG=test
TUNNEL_TOKEN=

SECRET_KEY=$secret_key
DEBUG=False
ALLOWED_HOSTS=api.lanceraos.com,localhost,127.0.0.1
FRONTEND_URL=https://lanceraos.com

DB_NAME=lanceraos_test
DB_USER=lanceraos_test
DB_PASSWORD=$db_password
DB_HOST=db
DB_PORT=5432

REDIS_URL=redis://redis:6379/1
CELERY_BROKER_URL=redis://redis:6379/0
CELERY_RESULT_BACKEND=redis://redis:6379/0
CHANNEL_LAYER_URL=redis://redis:6379/2

COOKIE_DOMAIN=.lanceraos.com
COOKIE_SECURE=True
COOKIE_SAMESITE=Lax
CORS_ALLOWED_ORIGINS=https://lanceraos.com
CSRF_TRUSTED_ORIGINS=https://lanceraos.com

SECURE_HSTS_SECONDS=3600
SECURE_HSTS_INCLUDE_SUBDOMAINS=True
SECURE_HSTS_PRELOAD=False

ENCRYPTION_KEY=$fernet
BLIND_INDEX_KEY=$blind

RESEND_API_KEY=
DEFAULT_FROM_EMAIL=LanceraOS <noreply@lanceraos.com>
RESEND_FROM_NAME=LanceraOS
CLOUDFLARE_WEBHOOK_SECRET=$webhook

GOOGLE_CLIENT_ID=
FACEBOOK_APP_ID=
FACEBOOK_APP_SECRET=
CLOUDINARY_CLOUD_NAME=
CLOUDINARY_API_KEY=
CLOUDINARY_API_SECRET=
GROQ_API_KEY=
SENTRY_DSN=
ENV
echo "Wrote $out (throwaway secrets, project lanceraos-test, port 18000)."
